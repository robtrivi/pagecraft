// AdvanceBold returns the bold glyph advance, or 500 if it is unknown.
func AdvanceBold(r rune) float64 {
	if w, ok := boldAdvances[r]; ok {
		return w
	}
	return 500
}

// MeasureBold sums Helvetica-Bold advances and scales the result to points.
func MeasureBold(s string, size float64) float64 {
	total := 0.0
	for _, r := range s {
		total += AdvanceBold(r)
	}
	return total / 1000 * size
}
